func buildTopProjectsTable(projects []TopProject) *rptgen.Table {
	rows := make([]map[string]any, len(projects))
	for i, p := range projects {
		rows[i] = map[string]any{
			"Project":    p.Key,
			"Count":      p.Count,
			"Percentage": fmt.Sprintf("%.2f%%", p.Percentage),
		}
	}
	return rptgen.NewTableWithColumns("Top 10 most analyzed projects", rows, []string{"Project", "Count", "Percentage"})
}

func buildLineChart(title string, series BranchExecutionTimeSeries) *rptgen.LineChart {
	pts := make([]rptgen.DataPoint, len(series.ExecutionTimesSeconds))
	for i, p := range series.ExecutionTimesSeconds {
		pts[i] = rptgen.DataPoint{Label: p.Label, Value: p.Seconds}
	}
	return rptgen.NewLineChartSingle(title, pts)
}

func sortedDays(m map[time.Time]map[string]int) []time.Time {
	days := make([]time.Time, 0, len(m))
	for d := range m {
		days = append(days, d)
	}
	sort.Slice(days, func(i, j int) bool { return days[i].Before(days[j]) })
	return days
}

func sortedDaysInt(m map[time.Time]int) []time.Time {
	days := make([]time.Time, 0, len(m))
	for d := range m {
		days = append(days, d)
	}
	sort.Slice(days, func(i, j int) bool { return days[i].Before(days[j]) })
	return days
}

func ordinal(n int) string {
	switch n {
	case 1:
		return "First"
	case 2:
		return "Second"
	case 3:
		return "Third"
	default:
		return fmt.Sprintf("%dth", n)
	}
}

