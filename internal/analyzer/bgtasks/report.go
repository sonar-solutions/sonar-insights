// --- recommendation ---

type capacityRecommendation struct {
	workersNeeded     int
	source            string
	bucketCount       int
	data              PercentileResult
	bucketLengthMin   int
	windowStart       time.Time
	windowEnd         time.Time
	allBucketsWorkers *int
	weekdayWorkers    *int
}

// findPercentileAnalyses locates the All-Buckets and Weekday analyses by label.
func findPercentileAnalyses(analyses []PercentileAnalysis) (*PercentileAnalysis, *PercentileAnalysis) {
	var allBuckets, weekday *PercentileAnalysis
	for i := range analyses {
		a := &analyses[i]
		if strings.Contains(a.Label, "All Buckets") {
			allBuckets = a
		} else if strings.Contains(a.Label, "Weekday") {
			weekday = a
		}
	}
	return allBuckets, weekday
}

// extractAtPercentile returns the PercentileResult and bucket count for a given percentile level.
func extractAtPercentile(a *PercentileAnalysis, p float64) (*PercentileResult, int) {
	if a == nil {
		return nil, 0
	}
	pr, ok := a.Percentiles[p]
	if !ok {
		return nil, 0
	}
	return &pr, a.BucketCount
}

func optionalWorkers(data *PercentileResult) *int {
	if data == nil {
		return nil
	}
	w := WorkersNeeded(data.SingleWorkerUtilization)
	return &w
}

func computeRecommendation(cap CapacityDemandResults) *capacityRecommendation {
	allBuckets, weekday := findPercentileAnalyses(cap.PercentileAnalyses)
	allData, allCount := extractAtPercentile(allBuckets, recommendationPercentile)
	weekData, weekCount := extractAtPercentile(weekday, recommendationPercentile)

	useWeekday := weekData != nil && (allData == nil || weekData.SingleWorkerUtilization > allData.SingleWorkerUtilization)
	var recData *PercentileResult
	var source string
	var count int
	if useWeekday {
		recData, source, count = weekData, "Weekday Buckets", weekCount
	} else {
		recData, source, count = allData, "All Buckets (24/7)", allCount
	}
	if recData == nil {
		return nil
	}

	return &capacityRecommendation{
		workersNeeded:     WorkersNeeded(recData.SingleWorkerUtilization),
		source:            source,
		bucketCount:       count,
		data:              *recData,
		bucketLengthMin:   cap.BucketLengthMinutes,
		windowStart:       cap.AnalysisWindowStart,
		windowEnd:         cap.AnalysisWindowEnd,
		allBucketsWorkers: optionalWorkers(allData),
		weekdayWorkers:    optionalWorkers(weekData),
	}
}

func writeRecommendationHTML(sb *strings.Builder, rec *capacityRecommendation) {
	if rec == nil {
		sb.WriteString("<p style='color: #757575; font-style: italic;'>Unable to generate recommendation - no percentile data available for the configured percentile.</p>")
		return
	}

	pLabel := fmt.Sprintf("%.0fth", recommendationPercentile*100)
	demandMin := rec.data.PercentileMs / 1000.0 / 60.0
	workerWord, areIs := "worker", "is"
	if rec.workersNeeded > 1 {
		workerWord, areIs = "workers", "are"
	}

	sb.WriteString("<h4 style='color: #2c3e50; margin-top: 20px;'>Recommendation</h4>")
	sb.WriteString("<div style='background-color: #e8f5e9; padding: 16px; border-left: 4px solid #4caf50; margin-bottom: 20px;'>")
	fmt.Fprintf(sb, "<p style='margin: 0; font-size: 1.05em;'><strong>Based on the %s percentile of capacity demand, <span style='color: #2e7d32;'>%d Compute Engine %s</span> %s recommended.</strong></p>",
		pLabel, rec.workersNeeded, workerWord, areIs)
	fmt.Fprintf(sb, "<p style='margin: 8px 0 0 0; color: #555;'>This configuration would handle %.0f%% of all time periods without queuing delays.</p>",
		recommendationPercentile*100)
	sb.WriteString(divClose)

	sb.WriteString("<h4 style='color: #2c3e50; margin-top: 20px;'>Summary</h4>")
	sb.WriteString("<ul style='line-height: 1.8; color: #333;'>")
	fmt.Fprintf(sb, "<li><strong>Percentile Used:</strong> %s</li>", pLabel)
	fmt.Fprintf(sb, "<li><strong>Demand at %s Percentile:</strong> %.2f min of work per %d-minute bucket</li>", pLabel, demandMin, rec.bucketLengthMin)
	fmt.Fprintf(sb, "<li><strong>Single Worker Utilization:</strong> %.1f%%</li>", rec.data.SingleWorkerUtilization)
	fmt.Fprintf(sb, "<li><strong>Data Source:</strong> %s (higher demand selected)</li>", rec.source)
	fmt.Fprintf(sb, "<li><strong>Buckets Analyzed:</strong> %d (%d-minute intervals)</li>", rec.bucketCount, rec.bucketLengthMin)
	if !rec.windowStart.IsZero() && !rec.windowEnd.IsZero() {
		fmt.Fprintf(sb, "<li><strong>Coverage Period:</strong> %.1f days</li>", rec.windowEnd.Sub(rec.windowStart).Hours()/24)
	}
	sb.WriteString("</ul>")
	writeWorkerComparisonNote(sb, rec)
}

func writeWorkerComparisonNote(sb *strings.Builder, rec *capacityRecommendation) {
	if rec.allBucketsWorkers == nil || rec.weekdayWorkers == nil {
		return
	}
	allW, wdW := *rec.allBucketsWorkers, *rec.weekdayWorkers
	if allW == wdW {
		return
	}
	sb.WriteString("<div style='background-color: #f5f5f5; padding: 12px; border-left: 3px solid #757575; margin-top: 10px; font-size: 0.95em;'>")
	fmt.Fprintf(sb, "<strong>Note:</strong> All Buckets (24/7) analysis suggests %d %s, while Weekday Buckets analysis suggests %d %s. The higher value was used for the recommendation.",
		allW, workerSuffix(allW), wdW, workerSuffix(wdW))
	sb.WriteString(divClose)
}

func workerSuffix(n int) string {
	if n == 1 {
		return "worker"
	}
	return "workers"
}

// --- detailed analysis table ---

func writeDetailedHTML(sb *strings.Builder, cap CapacityDemandResults) {
	allBuckets, weekday := findPercentileAnalyses(cap.PercentileAnalyses)
	if allBuckets == nil && weekday == nil {
		sb.WriteString("<p>No percentile analysis data available.</p>")
		return
	}
	levels := collectPercentileLevels(allBuckets, weekday)

	sb.WriteString("<h4 style='color: #2c3e50; margin-top: 25px;'>Capacity Demand Comparison</h4>")
	sb.WriteString("<table style='border-collapse: collapse; width: 100%; margin-bottom: 20px;'>")
	writeDetailedTableHeader(sb, allBuckets, weekday)
	writeDetailedTableBody(sb, levels, allBuckets, weekday)
	sb.WriteString("</table>")
	writeCapacityPlanningNotes(sb, allBuckets)
}

func collectPercentileLevels(analyses ...*PercentileAnalysis) []float64 {
	levelSet := make(map[float64]struct{})
	for _, a := range analyses {
		if a == nil {
			continue
		}
		for p := range a.Percentiles {
			levelSet[p] = struct{}{}
		}
	}
	levels := make([]float64, 0, len(levelSet))
	for p := range levelSet {
		levels = append(levels, p)
	}
	sort.Float64s(levels)
	return levels
}

func writeDetailedTableHeader(sb *strings.Builder, allBuckets, weekday *PercentileAnalysis) {
	sb.WriteString("<thead><tr style='background-color: #5a67d8; color: white;'>")
	sb.WriteString("<th style='padding: 12px; text-align: left; font-weight: 600; border-right: 1px solid #ddd;' rowspan='2'>Percentile</th>")
	if allBuckets != nil {
		sb.WriteString("<th style='padding: 12px; text-align: center; font-weight: 600; border-right: 1px solid #ddd;' colspan='3'>All Buckets (24/7)</th>")
	}
	if weekday != nil {
		sb.WriteString("<th style='padding: 12px; text-align: center; font-weight: 600;' colspan='3'>Weekday Buckets Only</th>")
	}
	sb.WriteString("</tr><tr style='background-color: #5a67d8; color: white; border-bottom: 2px solid #ddd;'>")
	if allBuckets != nil {
		writeHeaderSubCols(sb, weekday != nil)
	}
	if weekday != nil {
		writeHeaderSubCols(sb, false)
	}
	sb.WriteString("</tr></thead>")
}

func writeHeaderSubCols(sb *strings.Builder, hasBorder bool) {
	borderStyle := ""
	if hasBorder {
		borderStyle = " border-right: 1px solid #ddd;"
	}
	sb.WriteString("<th style='padding: 12px; text-align: right; font-weight: 600;'>Demand per Bucket</th>")
	sb.WriteString("<th style='padding: 12px; text-align: right; font-weight: 600;'>Workers Needed</th>")
	fmt.Fprintf(sb, "<th style='padding: 12px; text-align: right; font-weight: 600;%s'>Single Worker Utilization</th>", borderStyle)
}

func writeDetailedTableBody(sb *strings.Builder, levels []float64, allBuckets, weekday *PercentileAnalysis) {
	sb.WriteString("<tbody>")
	for _, p := range levels {
		writeDetailedTableRow(sb, p, allBuckets, weekday)
	}
	sb.WriteString("</tbody>")
}

func writeDetailedTableRow(sb *strings.Builder, p float64, allBuckets, weekday *PercentileAnalysis) {
	pLabel := fmt.Sprintf("%.1fth", p*100)
	if p == 1.0 {
		pLabel = "100th (Max)"
	}
	rowColor := "#f8f9fa"
	if maxPercentileUtil(p, allBuckets, weekday) > 100 {
		rowColor = "#fff3cd"
	}
	fmt.Fprintf(sb, "<tr style='border-bottom: 1px solid #eee; background-color: %s;'>", rowColor)
	fmt.Fprintf(sb, "<td style='padding: 10px; border-right: 1px solid #ddd;'><strong>%s</strong></td>", pLabel)
	if allBuckets != nil {
		writeAnalysisCells(sb, allBuckets, p, weekday != nil)
	}
	if weekday != nil {
		writeAnalysisCells(sb, weekday, p, false)
	}
	sb.WriteString("</tr>")
}

func maxPercentileUtil(p float64, analyses ...*PercentileAnalysis) float64 {
	max := 0.0
	for _, a := range analyses {
		if a == nil {
			continue
		}
		if pr, ok := a.Percentiles[p]; ok && pr.SingleWorkerUtilization > max {
			max = pr.SingleWorkerUtilization
		}
	}
	return max
}

func writeAnalysisCells(sb *strings.Builder, a *PercentileAnalysis, p float64, hasBorder bool) {
	borderStyle := ""
	if hasBorder {
		borderStyle = " border-right: 1px solid #ddd;"
	}
	if pr, ok := a.Percentiles[p]; ok {
		fmt.Fprintf(sb, "<td style='padding: 10px; text-align: right;'>%.2f min</td>", pr.PercentileMs/1000.0/60.0)
		fmt.Fprintf(sb, "<td style='padding: 10px; text-align: right;'>%d</td>", WorkersNeeded(pr.SingleWorkerUtilization))
		fmt.Fprintf(sb, "<td style='padding: 10px; text-align: right;%s'>%.2f%%</td>", borderStyle, pr.SingleWorkerUtilization)
	} else {
		fmt.Fprintf(sb, "<td style='padding: 10px; text-align: right;'>-</td>")
		fmt.Fprintf(sb, "<td style='padding: 10px; text-align: right;'>-</td>")
		fmt.Fprintf(sb, "<td style='padding: 10px; text-align: right;%s'>-</td>", borderStyle)
	}
}

